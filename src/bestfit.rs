/// Returns the byte libhtp writes for `codepoint`: the code point itself
/// below U+0100, its best-fit byte up to U+FFFF, and the replacement byte
/// otherwise.
pub(crate) fn byte_for(codepoint: u32) -> u8 {
    if let Ok(byte) = u8::try_from(codepoint) {
        return byte;
    }
    let Ok(codepoint) = u16::try_from(codepoint) else {
        return REPLACEMENT;
    };
    MAP.binary_search_by_key(&codepoint, |&(c, _)| c)
        .ok()
        .and_then(|i| MAP.get(i))
        .map_or(REPLACEMENT, |&(_, b)| b)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn map_is_sorted_and_ascii() {
        assert!(MAP.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(MAP.iter().all(|&(c, b)| c >= 0x100 && b.is_ascii()));
    }

    #[test]
    fn lookups() {
        assert_eq!(byte_for(0x41), b'A');
        assert_eq!(byte_for(0xe9), 0xe9);
        assert_eq!(byte_for(0x0100), b'A');
        assert_eq!(byte_for(0xff0f), b'/');
        assert_eq!(byte_for(0x017a), REPLACEMENT);
        assert_eq!(byte_for(0x4e00), REPLACEMENT);
        assert_eq!(byte_for(0x1_f600), REPLACEMENT);
    }
}
